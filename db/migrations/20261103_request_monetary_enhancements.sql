-- Run explicitly using the deployment migration procedure, before enabling the flags.
-- No existing request, policy binding or request-type configuration is rewritten.
BEGIN;
ALTER TABLE workflow_request_types ADD COLUMN IF NOT EXISTS monetary_routing_enabled boolean NOT NULL DEFAULT false;

-- Hibernate's old enum CHECK may prohibit the two new values. Replace only checks
-- on this single enum column; preserve checks involving other columns.
DO $$ DECLARE c record; BEGIN
  FOR c IN SELECT conname FROM pg_constraint
    WHERE conrelid = 'workflow_requests'::regclass AND contype = 'c'
      AND conkey = ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid='workflow_requests'::regclass AND attname='request_type')]::smallint[]
      AND pg_get_constraintdef(oid) LIKE '%STAFF_REQUISITION%'
  LOOP EXECUTE format('ALTER TABLE workflow_requests DROP CONSTRAINT %I',c.conname); END LOOP;
  ALTER TABLE workflow_requests ADD CONSTRAINT ck_workflow_request_type_money
    CHECK(request_type IN ('STAFF_REQUISITION','FILE_REQUEST','ASSET_REQUEST','EXPENSE_REIMBURSEMENT','GENERAL_REQUEST','CASH_ADVANCE','FUND_REQUEST'));
END $$;

CREATE TABLE IF NOT EXISTS request_monetary_policies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    version bigint,
    family_key varchar(36) NOT NULL, revision integer NOT NULL, name varchar(100) NOT NULL,
    request_type varchar(40) NOT NULL, currency varchar(3) NOT NULL, state varchar(20) NOT NULL,
    enabled boolean NOT NULL, published_by bigint, published_at timestamp,
    CONSTRAINT uk_monetary_policy_revision UNIQUE(family_key, revision)
);

CREATE TABLE IF NOT EXISTS request_monetary_bands (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    version bigint,
    policy_id bigint NOT NULL REFERENCES request_monetary_policies(id), ordinal integer NOT NULL,
    lower_bound numeric(19,2) NOT NULL CHECK(lower_bound >= 0), upper_bound numeric(19,2),
    target varchar(20) NOT NULL CHECK(target IN ('LINE_MANAGER','GROUPED')),
    grouped_version_id bigint REFERENCES grouped_approval_versions(id),
    CONSTRAINT uk_monetary_band_order UNIQUE(policy_id,ordinal),
    CHECK(upper_bound IS NULL OR upper_bound > lower_bound),
    CHECK((target = 'GROUPED') = (grouped_version_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS request_monetary_bindings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    version bigint,
    request_type varchar(40) NOT NULL, currency varchar(3) NOT NULL,
    policy_id bigint NOT NULL REFERENCES request_monetary_policies(id),
    CONSTRAINT uk_monetary_binding UNIQUE(request_type,currency)
);

CREATE TABLE IF NOT EXISTS request_monetary_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    version bigint,
    request_id bigint NOT NULL REFERENCES workflow_requests(id), submission_no integer NOT NULL,
    policy_id bigint NOT NULL REFERENCES request_monetary_policies(id),
    band_id bigint NOT NULL REFERENCES request_monetary_bands(id), policy_name varchar(140) NOT NULL,
    amount numeric(19,2) NOT NULL CHECK(amount > 0), currency varchar(3) NOT NULL,
    lower_bound numeric(19,2) NOT NULL, upper_bound numeric(19,2), target varchar(20) NOT NULL,
    grouped_version_id bigint REFERENCES grouped_approval_versions(id), resolved_route text NOT NULL,
    workflow_instance_id varchar(100), submitted_by bigint NOT NULL,
    CONSTRAINT uk_monetary_request_submission UNIQUE(request_id,submission_no)
);

CREATE TABLE IF NOT EXISTS request_monetary_policy_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    version bigint,
    policy_id bigint REFERENCES request_monetary_policies(id), request_type varchar(40) NOT NULL,
    action varchar(40) NOT NULL, actor_id bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS request_cash_advance_details (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    version bigint,
    request_id bigint NOT NULL UNIQUE REFERENCES workflow_requests(id),
    amount numeric(19,2) NOT NULL CHECK(amount > 0), currency varchar(3) NOT NULL,
    purpose varchar(2000) NOT NULL, cost_center varchar(100) NOT NULL, required_date date NOT NULL,
    expense_start_date date NOT NULL, expense_end_date date NOT NULL, settlement_due_date date NOT NULL,
    CHECK(required_date <= expense_start_date AND expense_start_date <= expense_end_date AND expense_end_date <= settlement_due_date)
);

CREATE TABLE IF NOT EXISTS request_fund_request_details (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    version bigint,
    request_id bigint NOT NULL UNIQUE REFERENCES workflow_requests(id),
    amount numeric(19,2) NOT NULL CHECK(amount > 0), currency varchar(3) NOT NULL,
    purpose varchar(2000) NOT NULL, cost_center varchar(100) NOT NULL, required_date date NOT NULL,
    beneficiary_employee_id bigint NOT NULL, beneficiary_name varchar(200) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_monetary_policy_events_recent ON request_monetary_policy_events(id DESC);
COMMIT;
